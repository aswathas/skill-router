#!/usr/bin/env python3
"""Generate the arXiv submission metadata from the paper itself.

The abstract must match the paper's abstract: arXiv shows a warning when the
abstract in the submission form differs from the one in the PDF. Reading it
from paper/content.py makes that impossible to get wrong and keeps the two in
step when the paper is edited.

Run after every paper rebuild:

    python arxiv/make-metadata.py
"""

import importlib.util
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PAPER = ROOT / "paper"
OUT = ROOT / "arxiv" / "metadata.yaml"

CATEGORIES = {
    "primary": "cs.AI",
    "cross": "cs.IR",
}


def load_content():
    spec = importlib.util.spec_from_file_location("content", PAPER / "content.py")
    mod = importlib.util.module_from_spec(spec)
    sys.modules["content"] = mod
    spec.loader.exec_module(mod)
    return mod


def yaml_quote(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def block(s, indent="  "):
    return "\n".join(indent + line for line in s.split("\n"))


def main():
    C = load_content()
    authors = "\n".join(
        "  - name: %s\n    affiliation: %s" % (yaml_quote(a), yaml_quote(C.AFFIL[0]))
        for a in C.AUTHORS
    )
    meta = f"""# arXiv submission metadata for "Capability Routing for Agent Skill Libraries"
#
# Generated by arxiv/make-metadata.py from paper/content.py - do not hand edit.
# Paste these values into the arXiv submission form.
# The abstract below is the paper's own abstract, verbatim: arXiv warns when
# the form abstract differs from the one in the PDF.

title: {yaml_quote(C.TITLE)}
subtitle: {yaml_quote(C.SUBTITLE)}

authors:
{authors}

abstract: |
{block(C.ABSTRACT)}

primary_category: {yaml_quote(CATEGORIES["primary"])}
cross_list_categories:
  - {yaml_quote(CATEGORIES["cross"])}

comments: "6 pages, 3 tables. Public artefact (router, capability taxonomy, 298-case evaluation harness and benchmark): https://github.com/aswathas/skill-router"

report_no: ""
doi: ""
"""
    OUT.write_text(meta, encoding="utf-8")
    print("wrote", OUT, OUT.stat().st_size, "bytes")
    print("abstract words:", len(C.ABSTRACT.split()))
    print("primary:", CATEGORIES["primary"], "cross:", CATEGORIES["cross"])


if __name__ == "__main__":
    main()
